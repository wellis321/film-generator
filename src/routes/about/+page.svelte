<h1 class="text-3xl font-black text-neutral-50 sm:text-4xl">Wait, why does this exist?</h1>

<div class="mt-6 max-w-2xl space-y-5 text-neutral-300">
	<p class="leading-relaxed">
		Every family has one. The film — or franchise, or decade-spanning cinematic universe — that
		everyone else seems to adore, quote endlessly, and rewatch on a loop, and you just...
		don't get it. You watched it. You paid attention. You even tried to like it. And somehow
		you walked away with more questions than answers: how did that timeline actually work? Why
		did nobody just <em>talk</em> to each other? Why does the villain's entire plan rely on nobody
		checking one very obvious thing?
	</p>

	<p class="leading-relaxed">
		This isn't a hit piece on anyone's favourite film. Genuinely — if you love it, that's
		wonderful, and we mean that. Taste is personal, and the things that move us often say more
		about us than about the movie. This site exists purely to log our side of the story: the
		reviews, the ratings, the bewilderment, honestly recorded, for an audience of exactly two.
		Well. Now you too, apparently.
	</p>

	<p class="leading-relaxed">
		So if you've ever sat through a beloved classic wondering aloud why the plot needed three
		prequels to make sense, noticed that a decades-old "hilarious" scene has aged like milk left
		in the sun, or spent an emotional climax quietly thinking <em>"huh, that was fine, I guess"</em>
		while everyone around you wept with joy — welcome. You're exactly who this was built for.
	</p>

	<p class="leading-relaxed">
		No malice here, just a family with a wheel, a database of very popular films, and a stubborn
		refusal to pretend we felt something we didn't.
	</p>

